import type { FoodDraft } from "./model";

export const foodLibraryRules = "食材库描述独立于餐次，只记录食物本身。名称和规格写食品身份、组成、营养基准数量与单位。估算依据按组成与分量、数据来源与计算、汇总结果说明，保留各成分的估计克数／范围、可核实的换算与具体不确定项；不能用一句笼统估算代替已有分析，也不能只重复营养表四项数字。只有标签或成分表时说明来源标识、采用条目与基准即可。缺少分项数据时保持未知，不倒推或编造精确克数、热量和计算过程。禁止写用户何时吃过、何时上传、要求入库、纠错对话等个人背景；不写熟重不可直接套用、必须调整等泛化提醒或未提及食物的排除清单。实际食用日期、食量、油酱和个人备注放餐次。";

/** 只检查本次写入的食材文本；既有餐项和个人餐次备注仍可保留自己的语境。 */
export function foodDescriptionProblem(food: Pick<FoodDraft, "name" | "brand" | "preparation" | "basis">): string | null {
  const text = [food.name, food.brand, food.preparation, food.basis].filter(Boolean).join("\n");
  if (/用户|(?:你|您)(?:今天|昨天|前天|本次|这次|当时|20\d{2})|(?:本次|这次|当时|今天|昨天|前天)(?:实际)?(?:吃了|吃过|食用|摄入)|不可直接套用|不能直接套用|必须调整|必须区分|须核对|不得重复计算/.test(text)) {
    return "食材说明含个人餐次背景或泛化提醒。请删除这些内容，保留食物组成、估计分量、来源、计算和结果；个人日期与食用情况写在餐次备注，不需为文案再次询问使用者。";
  }
  return null;
}
