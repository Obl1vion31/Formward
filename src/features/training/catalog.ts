export function searchExercises(query = '', category = '', body = '', equipment = '') {
  const words = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return exerciseCatalog.filter(e => (!category || e.category === category) && (!body || e.bodyParts.includes(body)) && (!equipment || e.equipment === equipment) && words.every(word => [e.name, e.english, ...e.aliases, ...e.bodyParts, e.equipment, e.pattern].join(' ').toLocaleLowerCase().includes(word)));
}
